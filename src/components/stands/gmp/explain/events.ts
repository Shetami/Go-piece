import type { EventType, SimEvent } from '../engine/types.ts'

/**
 * Разбор событий стенда.
 *
 * Объяснения привязаны к ТИПУ события, а не к кадру анимации: какой бы
 * сценарий ни крутился, клик по «p.stole» откроет один и тот же разбор,
 * подставив в него конкретные G/M/P из payload.
 */

export interface Explanation {
  /** Одна строка для ленты: «P2 украл 3 горутины у P0». */
  title: string
  /** Подробный разбор — абзацы. */
  body: string[]
  /** Что делает настоящий рантайм — функции из src/runtime/proc.go. */
  runtime?: string
  /** Где модель расходится с реальностью, если это важно для понимания. */
  model?: string
  /** id терминов справочника. */
  terms: string[]
}

const g = (e: SimEvent, i = 0) => `G${e.actors.g?.[i] ?? '?'}`
const m = (e: SimEvent, i = 0) => `M${e.actors.m?.[i] ?? '?'}`
const p = (e: SimEvent, i = 0) => `P${e.actors.p?.[i] ?? '?'}`
const num = (v: unknown) => (typeof v === 'number' ? v : Number(v ?? 0))

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
const goroutines = (n: number) => `${n} ${plural(n, 'горутину', 'горутины', 'горутин')}`
const ticks = (n: number) => `${n} ${plural(n, 'тик', 'тика', 'тиков')}`

