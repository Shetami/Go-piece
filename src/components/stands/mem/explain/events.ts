/**
 * Разбор событий стенда.
 *
 * Объяснения привязаны к ТИПУ события, а не к кадру: какой бы сценарий ни
 * крутился, клик по «central.contended» откроет один и тот же разбор,
 * подставив в него конкретные горутины, классы и страницы из payload.
 */

export interface Explanation {
  title: string
  body: string[]
  /** Что делает настоящий рантайм — функции из runtime/malloc.go и соседних файлов. */
  runtime?: string
  /** Где модель расходится с реальностью, если это важно для понимания. */
  model?: string
  terms: string[]
}

const num = (v: unknown) => (typeof v === 'number' ? v : Number(v ?? 0))
const g = (e: MemEvent, i = 0) => `G${e.actors.g?.[i] ?? '?'}`
const p = (e: MemEvent, i = 0) => `P${e.actors.p?.[i] ?? '?'}`

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
const objects = (n: number) => `${n} ${plural(n, 'объект', 'объекта', 'объектов')}`
const pages = (n: number) => `${n} ${plural(n, 'страницу', 'страницы', 'страниц')}`
const bytes = (n: number) => (n >= 1024 ? `${Math.round((n / 1024) * 10) / 10} КБ` : `${n} Б`)

