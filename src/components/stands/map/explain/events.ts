export interface Explanation {
  title: string
  body: string[]
  /** Что делает настоящий рантайм — функции из internal/runtime/maps или runtime/map.go. */
  runtime?: string
  /** Где модель расходится с реальностью, если это важно для понимания. */
  model?: string
  terms: string[]
}

const num = (v: unknown) => (typeof v === 'number' ? v : Number(v ?? 0))
const str = (v: unknown) => (typeof v === 'string' ? v : String(v ?? ''))

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
const groups = (n: number) => `${n} ${plural(n, 'группу', 'группы', 'групп')}`
const slots = (n: number) => `${n} ${plural(n, 'слот', 'слота', 'слотов')}`
const records = (n: number) => `${n} ${plural(n, 'запись', 'записи', 'записей')}`
const buckets = (n: number) => `${n} ${plural(n, 'корзина', 'корзины', 'корзин')}`
/** Ключ так, как он выглядит в коде. */
const k = (e: MapEvent, field = 'key') => (str(e.payload[field]) === 'NaN' ? 'NaN' : `"${str(e.payload[field])}"`)
const legacy = (e: MapEvent) => Boolean(e.payload.legacy) || e.payload.impl === 'legacy'

