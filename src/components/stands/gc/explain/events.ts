/**
 * Разбор событий стенда.
 *
 * Объяснения привязаны к ТИПУ события, а не к кадру: какой бы сценарий ни
 * крутился, клик по «barrier.missed» откроет один и тот же разбор, подставив
 * в него конкретные блоки и горутины из payload.
 */

export interface Explanation {
  /** Одна строка для ленты: «Барьер закрасил #37 — объект спасён». */
  title: string
  /** Подробный разбор — абзацы. */
  body: string[]
  /** Что делает настоящий рантайм — функции из src/runtime/mgc.go и соседних файлов. */
  runtime?: string
  /** Где модель расходится с реальностью, если это важно для понимания. */
  model?: string
  /** id терминов справочника. */
  terms: string[]
}

const num = (v: unknown) => (typeof v === 'number' ? v : Number(v ?? 0))
const cell = (e: GcEvent, i = 0) => `#${e.actors.cells?.[i] ?? '?'}`
const mut = (e: GcEvent, i = 0) => `G${e.actors.mut?.[i] ?? '?'}`

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
const blocks = (n: number) => `${n} ${plural(n, 'блок', 'блока', 'блоков')}`
const ticks = (n: number) => `${n} ${plural(n, 'тик', 'тика', 'тиков')}`

