import type { LoadEvent, LoadEventType } from '../engine/types.ts'

/**
 * Разбор событий стенда. Объяснения привязаны к ТИПУ события: какой бы
 * сценарий ни крутился, клик по «req.wasted» откроет один и тот же разбор,
 * подставив в него конкретные запросы, воркеры и числа из payload.
 */

export interface Explanation {
  title: string
  body: string[]
  /** Как это выглядит в сервисе на Go. */
  go?: string
  model?: string
  terms: string[]
}

const num = (v: unknown) => (typeof v === 'number' ? v : Number(v ?? 0))

function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
const ticks = (n: number) => `${n} ${plural(n, 'тик', 'тика', 'тиков')}`
const reqs = (n: number) => `${n} ${plural(n, 'запрос', 'запроса', 'запросов')}`
const tries = (n: number) => `${n} ${plural(n, 'попытка', 'попытки', 'попыток')}`
const pct = (v: unknown) => `${Math.round(num(v) * 100)}%`
const worker = (v: unknown) => `воркер ${num(v) + 1}`

