/**
 * Формат тестов «Проверь себя» в конце лекций.
 *
 * Один тест — один модуль src/data/quizzes/<курс>/<лекция>.ts с default-экспортом
 * типа Quiz; путь повторяет id лекции. Вопросы — TypeScript, а не YAML: так формат
 * проверяет компилятор, а тест целостности импортирует их без парсеров.
 *
 * В тексте вопросов, вариантов и разборов работает минимальная разметка:
 * `код` и **жирный**. Остальное выводится как есть.
 *
 * В отличие от задач практики, ответы здесь не секрет: это самопроверка, и
 * разбор показывается сразу после ответа. Поэтому всё уезжает на клиент.
 */

export type Question =
  /**
   * Один правильный вариант. answer — его индекс, с нуля. На странице варианты
   * перемешиваются, так что место правильного в списке не важно.
   */
  | { kind: 'single'; q: string; options: string[]; answer: number; explain: string }
  /** Несколько правильных. answer — индексы всех правильных; засчитывается только точное совпадение. */
  | { kind: 'multi'; q: string; options: string[]; answer: number[]; explain: string }
  /** Утверждение: верно или нет. */
  | { kind: 'truefalse'; q: string; answer: boolean; explain: string }
  /** Расставить по порядку. items записаны В ПРАВИЛЬНОМ порядке — на странице они перемешиваются. */
  | { kind: 'order'; q: string; items: string[]; explain: string }

export type QuestionKind = Question['kind']

export interface Quiz {
  questions: Question[]
}
