import "fmt"

// SyntaxError — ошибка разбора командной строки; Pos — позиция в символах
// (рунах, с нуля).
type SyntaxError struct {
	Pos int
	Msg string
}

func (e *SyntaxError) Error() string { return fmt.Sprintf("символ %d: %s", e.Pos, e.Msg) }

