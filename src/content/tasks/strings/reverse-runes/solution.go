package main

// Reverse возвращает строку, записанную задом наперёд.
// Считать надо символами, а не байтами: "Привет" → "тевирП".
func Reverse(s string) string {
	// []rune разбивает строку по символам. Разворот по байтам порвал бы
	// многобайтовые руны: на выходе получился бы мусор, а не текст.
	r := []rune(s)
	for i, j := 0, len(r)-1; i < j; i, j = i+1, j-1 {
		r[i], r[j] = r[j], r[i]
	}
	return string(r)
}
