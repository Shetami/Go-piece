// CSVError — ошибка в записи, которая начинается на строке Line (с 1).
type CSVError struct {
	Line int
	Err  error
}

func (e *CSVError) Error() string { return fmt.Sprintf("csv, строка %d: %v", e.Line, e.Err) }
func (e *CSVError) Unwrap() error { return e.Err }

