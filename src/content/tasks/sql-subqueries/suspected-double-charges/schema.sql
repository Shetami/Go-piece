CREATE TABLE merchants (
  id   int PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE charges (
  id          int PRIMARY KEY,
  merchant_id int NOT NULL REFERENCES merchants (id),
  card        text NOT NULL,
  amount      numeric(10, 2) NOT NULL,
  charged_at  timestamp NOT NULL,
  status      text NOT NULL          -- 'ok', 'declined'
);

