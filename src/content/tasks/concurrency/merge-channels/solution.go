package main

import "sync"

// Merge объединяет значения из всех входных каналов в один.
//
// Схема стандартная: на каждый вход — своя горутина, которая перекладывает
// значения в общий выходной канал. WaitGroup считает, сколько входов ещё живо;
// отдельная горутина ждёт их всех и закрывает выход. Закрывать выход из
// перекладывающих горутин нельзя — закроет первая же, а остальные упадут на
// отправке в закрытый канал.
func Merge(chans ...<-chan int) <-chan int {
	out := make(chan int)

	var wg sync.WaitGroup
	wg.Add(len(chans))

	for _, ch := range chans {
		go func(ch <-chan int) {
			defer wg.Done()
			for v := range ch {
				out <- v
			}
		}(ch)
	}

	// Без своей горутины здесь был бы дедлок: Wait не дождётся отправителей,
	// пока их никто не читает, а читать начнут только после возврата из Merge.
	go func() {
		wg.Wait()
		close(out)
	}()

	return out
}
