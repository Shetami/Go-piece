package main

// Lazy лениво вычисляет значение через init.
type Lazy[T any] struct {
	init func() (T, error)
	// ваши поля
}

func NewLazy[T any](init func() (T, error)) *Lazy[T] {
	return &Lazy[T]{init: init}
}

