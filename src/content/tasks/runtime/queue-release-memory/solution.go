package main

// Queue — FIFO-очередь на слайсе. Нулевое значение готово к работе.
// Не обязана быть потокобезопасной.
//
// Требования к памяти:
//   - очередь не удерживает извлечённые элементы: если T содержит указатели,
//     то после Pop объект может быть собран сборщиком мусора;
//   - после каждого Pop выполняется Cap() <= max(64, 4*Len()): очередь,
//     которая однажды выросла до миллиона элементов, а потом опустела,
//     не держит миллионный массив.
type Queue[T any] struct {
	buf  []T // живые элементы — buf[head:]
	head int
}

// Push добавляет v в конец очереди. Амортизированно O(1).
func (q *Queue[T]) Push(v T) {
	q.buf = append(q.buf, v)
}

// Pop извлекает элемент из начала. Для пустой очереди — нулевое значение и false.
// Амортизированно O(1).
func (q *Queue[T]) Pop() (T, bool) {
	var zero T
	if q.head == len(q.buf) {
		return zero, false
	}
	v := q.buf[q.head]
	// Обнуляем слот: иначе массив продолжает ссылаться на объект,
	// и сборщик мусора его не освободит.
	q.buf[q.head] = zero
	q.head++

	n := q.Len()
	switch {
	case n == 0:
		// Пусто: отпускаем массив целиком, если он большой, иначе переиспользуем.
		if cap(q.buf) > 64 {
			q.buf = nil
		} else {
			q.buf = q.buf[:0]
		}
		q.head = 0
	case cap(q.buf) > max(64, 4*n):
		// Живых мало, массив велик — переезжаем в новый поменьше.
		// Копия стоит O(n), но случается после ~cap/2 Pop — амортизированно O(1).
		nb := make([]T, n, 2*n)
		copy(nb, q.buf[q.head:])
		q.buf, q.head = nb, 0
	}
	return v, true
}

// Len — число элементов в очереди.
func (q *Queue[T]) Len() int { return len(q.buf) - q.head }

// Cap — вместимость внутреннего буфера в элементах (сколько памяти держит очередь).
func (q *Queue[T]) Cap() int { return cap(q.buf) }
