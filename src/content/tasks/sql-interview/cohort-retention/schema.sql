CREATE TABLE users (
  id            int PRIMARY KEY,
  name          text NOT NULL,
  signed_up_at  timestamp NOT NULL
);

CREATE TABLE orders (
  id          int PRIMARY KEY,
  user_id     int NOT NULL REFERENCES users(id),
  created_at  timestamp NOT NULL,
  status      text NOT NULL, -- done, cancelled, refunded
  amount      int NOT NULL
);

