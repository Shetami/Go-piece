-- Оплаченные периоды доступа; обе даты включительно.
-- Периоды бывают вложенными, смежными и с одинаковым началом.
CREATE TABLE periods (
  id        int PRIMARY KEY,
  customer  text NOT NULL,
  starts_on date NOT NULL,
  ends_on   date NOT NULL CHECK (ends_on >= starts_on)
);

