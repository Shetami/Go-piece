CREATE TABLE users (
  id   int PRIMARY KEY,
  name text NOT NULL
);

-- Плеер раз в минуту шлёт heartbeat, пока идёт просмотр.
-- При сбое сети heartbeat может прийти повторно с тем же ts.
CREATE TABLE heartbeats (
  user_id    int       NOT NULL REFERENCES users (id),
  content_id int       NOT NULL,
  ts         timestamp NOT NULL
);

