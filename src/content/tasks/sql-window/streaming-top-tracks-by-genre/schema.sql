CREATE TABLE tracks (
  id    int PRIMARY KEY,
  title text NOT NULL,
  genre text            -- у демо-записей жанр не указан
);

CREATE TABLE plays (
  id        int PRIMARY KEY,
  track_id  int       NOT NULL REFERENCES tracks (id),
  user_id   int       NOT NULL,
  played_at timestamp NOT NULL,
  seconds   int       NOT NULL   -- сколько секунд слушали
);

