package main

// After возвращает функцию, которая первые n-1 вызовов ничего не делает,
// а начиная с n-го вызывает f. Для n <= 1 f вызывается с первого раза.
// Каждая функция, возвращённая After, считает свои вызовы сама.
func After(n int, f func()) func() {
	// Счётчик снаружи возвращаемого замыкания: он живёт между вызовами
	// и у каждого результата After свой.
	calls := 0
	return func() {
		calls++
		if calls >= n {
			f()
		}
	}
}
