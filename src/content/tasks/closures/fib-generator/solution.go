package main

// FibGen возвращает генератор: каждый вызов отдаёт следующее число Фибоначчи,
// начиная с 0: 0, 1, 1, 2, 3, 5, ...
func FibGen() func() int {
	a, b := 0, 1
	return func() int {
		// Возвращаем текущее и сдвигаем пару одним параллельным присваиванием.
		cur := a
		a, b = b, a+b
		return cur
	}
}
