CREATE TABLE stores (
  id        int PRIMARY KEY,
  name      text NOT NULL,
  opened_on date NOT NULL,
  closed_on date           -- первый день, когда магазин уже не работает; NULL — работает
);

-- store_id пуст у чеков интернет-кассы, которые не относятся к магазину
CREATE TABLE sales (
  id       int PRIMARY KEY,
  store_id int REFERENCES stores (id),
  sold_at  timestamp NOT NULL,
  amount   numeric   NOT NULL
);

